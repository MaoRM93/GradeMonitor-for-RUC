String majorPinyin(String name) => kMajorPinyin[name] ?? name;

/// 首字母分组键：取拼音第一个字母并大写，非 A–Z 统一归到 '#'。
String majorInitial(String name) {
  final pinyin = majorPinyin(name);
  if (pinyin.isEmpty) return '#';
  final first = pinyin.substring(0, 1).toUpperCase();
  return RegExp(r'^[A-Z]$').hasMatch(first) ? first : '#';
}
